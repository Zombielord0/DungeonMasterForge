// Shop generator on the Items tab. Run with:  npm run test:shop
const http = require("http"), fs = require("fs"), path = require("path");
const { chromium } = require("playwright");
const ROOT = path.join(__dirname, "..", "..", "public");
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".json": "application/json", ".css": "text/css", ".png": "image/png" };
let fails = 0;
const check = (name, ok, extra = "") => { console.log((ok ? "PASS " : "FAIL ") + name + (ok || !extra ? "" : "  -> " + extra)); if (!ok) fails++; };
const server = http.createServer((req, res) => {
  const u = new URL(req.url, "http://x"), f = path.join(ROOT, u.pathname === "/" ? "index.html" : decodeURIComponent(u.pathname));
  if (!f.startsWith(ROOT)) { res.writeHead(403); return res.end(); }
  fs.readFile(f, (e, b) => { if (e) { res.writeHead(404); return res.end(); } res.writeHead(200, { "content-type": TYPES[path.extname(f)] || "application/octet-stream" }); res.end(b); });
});

(async () => {
  await new Promise(r => server.listen(0, r));
  const URL = `http://localhost:${server.address().port}/`;
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1400, height: 1000 }, serviceWorkers: "block" });
  await ctx.addInitScript(() => localStorage.setItem("dmforge.offline", "1"));
  const errs = [];
  const p = await ctx.newPage(); p.on("pageerror", e => errs.push(e.message));
  await p.goto(URL); await p.waitForFunction(() => typeof generateCharacter === "function");
  await p.evaluate(() => { currentPC = pcEnsure(generateCharacter({ seed: "SHOP1", name: "Brom", ed: "2024" })); keepPC(); PCS.roster[0].coins = { cp: 0, sp: 0, ep: 0, gp: 500, pp: 0 }; pcPersist(); });
  await p.goto(URL + "#items"); await p.waitForTimeout(300);

  // the rules: what each kind of shop stocks
  const r = await p.evaluate(() => {
    const out = {};
    const a = shopMake({ type: "smith", size: "town", level: 3, seed: "S1", ed: "2024" }), b = shopMake({ type: "smith", size: "town", level: 3, seed: "S1", ed: "2024" });
    out.same = JSON.stringify(a) === JSON.stringify(b);
    out.smithOk = a.stock.length >= 6 && a.stock.every(x => /Weapon|Armor/.test(x.cat + " " + (x.g || "")));
    out.named = !!a.name && !!a.keeper && !!a.mood;
    out.priced = a.stock.every(x => x.gp > 0 && x.qty >= 1);
    const v = shopMake({ type: "magic", size: "village", level: 3, seed: "S2", ed: "2014" }), c = shopMake({ type: "magic", size: "city", level: 12, seed: "S2", ed: "2014" });
    out.villageMagic = v.stock.filter(x => x.kind === "magic").every(x => x.rk <= 1) && v.stock.length <= 6;
    out.cityMagic = c.stock.some(x => x.kind === "magic" && x.rk >= 2) && c.stock.length > v.stock.length;
    const alc = shopMake({ type: "alchemist", size: "town", level: 3, seed: "S3", ed: "2014" });
    out.alchemist = alc.stock.some(x => /potion|acid|antitoxin|alchemist|healer|herbal/i.test(x.n));
    const big = shopMake({ type: "general", size: "city", level: 3, seed: "S4", ed: "2024" }), small = shopMake({ type: "general", size: "village", level: 3, seed: "S4", ed: "2024" });
    out.sizes = big.stock.length > small.stock.length;
    // new options (2026-11-17): rarity, amount, manner
    const o1 = shopMake({ type: "smith", size: "town", level: 3, seed: "S1", ed: "2024" }), o2 = shopMake({ type: "smith", size: "town", level: 3, seed: "S1", ed: "2024", amount: undefined, rar: undefined });
    out.old = JSON.stringify(o1) === JSON.stringify(o2) && o1.stock.map(x => x.id).join() === "2024-g48,2024-g69,2024-g76,2024-g82,2024-g87,2024-g90,2024-g113,2024-g142,2024-g146,2024-g152";
    const ro = shopMake({ type: "magic", size: "city", level: 12, seed: "R1", ed: "2014", rar: [2] }).stock.filter(x => x.kind === "magic");
    out.rarOnly = ro.length >= 2 && ro.every(x => x.rk === 2);
    const rs = shopMake({ type: "smith", size: "village", level: 1, seed: "R2", ed: "2024", rar: [1] }).stock.filter(x => x.kind === "magic");
    out.rarSmith = rs.length >= 2 && rs.every(x => x.rk === 1);
    out.rarGeneral = shopMake({ type: "general", size: "town", level: 3, seed: "R3", ed: "2024", rar: [3] }).stock.every(x => x.kind !== "magic");
    const am = k => shopMake({ type: "general", size: "city", level: 3, seed: "A1", ed: "2024", amount: k }).stock.length;
    out.amount = am("small") >= 1 && am("small") < am("normal") && am("normal") < am("large");
    const m1 = shopMake({ type: "general", size: "town", level: 3, seed: "M1", ed: "2024", moodIx: 1 }), m0 = shopMake({ type: "general", size: "town", level: 3, seed: "M1", ed: "2024" });
    out.mood = m1.mood === SHOP_MOODS[1][0] && m1.moodIx === 1 && Number.isInteger(m0.moodIx) && SHOP_MOODS[m0.moodIx][0] === m0.mood;
    const m4 = shopMake({ type: "general", size: "town", level: 3, seed: "M2", ed: "2024", moodIx: 4 }), g = m4.stock[0], base = IT.data["2024"].find(x => x.id === g.id);
    out.moodPrice = g.gp === shopNiceGp(+base.gp * 1.25);
    return out;
  });
  check("old shops keep their stock (same seed, no new options)", r.old);
  check("a rarity choice gives only that rarity, at least 2", r.rarOnly);
  check("a rarity choice puts magic items in a village smithy", r.rarSmith);
  check("a rarity choice adds no magic to a general store", r.rarGeneral);
  check("small < normal < large stock", r.amount);
  check("a chosen manner is used and remembered", r.mood);
  check("the manner sets the prices", r.moodPrice);
  check("the same seed makes the same shop", r.same);
  check("a blacksmith sells weapons and armor", r.smithOk);
  check("a shop has a name, a shopkeeper and a manner", r.named);
  check("everything has a price and a quantity", r.priced);
  check("a village magic shop has only common or uncommon items", r.villageMagic);
  check("a city magic shop has rarer items and more of them", r.cityMagic);
  check("an alchemist sells potions and the like", r.alchemist);
  check("cities have bigger shops than villages", r.sizes);

  // a saved World shop: stock kept, markup, own prices, restock (2026-11-17)
  await p.evaluate(() => { PCS.roster[0].coins = { cp: 0, sp: 0, ep: 0, gp: 100000, pp: 0 }; pcPersist(); });
  const pid = await p.evaluate(() => {
    const sh = shopMake({ type: "smith", size: "town", level: 3, seed: "OLD1", ed: "2024" });
    const legacy = sh.stock.slice(0, 24).map(x => `- ${x.n}: ${x.c}${x.kind === "magic" ? " (magic)" : ""}`).join("\n");
    const pl = wpNew({ name: "Old Shop", type: "shop", shop: { type: "smith", size: "town", level: 3, seed: "OLD1", ed: "2024" }, sections: [{ t: "For sale", x: legacy, dm: false }] });
    worldSave(); return pl.id;
  });
  await p.evaluate(id => shopOpen(wp(id)), pid); await p.waitForTimeout(300);
  const mig = await p.evaluate(id => { const pl = wp(id), ref = shopMake({ type: "smith", size: "town", level: 3, seed: "OLD1", ed: "2024" }); return { ids: pl.shop.stock.map(x => x.id).join() === ref.stock.map(x => x.id).join(), auto: !!pl.sections[0].auto, name: pl.name === "Old Shop", open: location.hash === "#items" && !$("#itShop").hidden && IT.shop === pl.shop }; }, pid);
  check("an older shop opens with the stock it always had", mig.ids && mig.open, JSON.stringify(mig));
  check("its For sale list is kept up to date", mig.auto);
  check("its name isn't changed", mig.name);
  check("the old kind/settlement/level selects are gone", !(await p.$("#shopType")) && !(await p.$("#shopReroll")));
  await p.fill("#shopMarkup", "20"); await p.waitForTimeout(400);
  const mk = await p.evaluate(id => { const s = wp(id).shop; return { shown: +$('[data-shopown="0"]').value, want: shopNiceGp(s.stock[0].gp * 1.2), saved: s.markup }; }, pid);
  check("markup changes the prices", mk.shown === mk.want, JSON.stringify(mk));
  check("markup is saved", mk.saved === 20);
  await p.fill('[data-shopown="1"]', "7"); await p.press('[data-shopown="1"]', "Tab"); await p.waitForTimeout(100);
  check("your own price is kept on the item", await p.evaluate(id => wp(id).shop.stock[1].own === 7 && !!document.querySelector('#itShop tr:nth-child(2) .shop-own'), pid));
  await p.fill("#shopMarkup", "50"); await p.waitForTimeout(400);
  const mk2 = await p.evaluate(id => { const s = wp(id).shop; return { own: +$('[data-shopown="1"]').value, r0: +$('[data-shopown="0"]').value, want: shopNiceGp(s.stock[0].gp * 1.5) }; }, pid);
  check("markup leaves your own price alone", mk2.own === 7 && mk2.r0 === mk2.want, JSON.stringify(mk2));
  await p.fill('[data-shopown="1"]', ""); await p.press('[data-shopown="1"]', "Tab"); await p.waitForTimeout(100);
  check("clearing your own price goes back to the markup price", await p.evaluate(id => wp(id).shop.stock[1].own === undefined, pid));
  const markupOf = async v => { await p.evaluate(v => { const f = $("#shopMarkup"); f.type = "text"; f.value = v; f.dispatchEvent(new Event("input", { bubbles: true })); f.type = "number"; }, v); await p.waitForTimeout(400); return p.evaluate(id => wp(id).shop.markup, pid); };
  check("markup stops at +500", await markupOf("9999") === 500);
  check("markup stops at -90", await markupOf("-500") === -90);
  check("a markup that isn't a number counts as 0", await markupOf("abc") === 0);
  await markupOf("20");
  await p.fill('[data-shopown="2"]', "-3"); await p.press('[data-shopown="2"]', "Tab"); await p.waitForTimeout(100);
  check("a price below 0 isn't kept", await p.evaluate(id => wp(id).shop.stock[2].own === undefined, pid));
  const it0 = await p.evaluate(id => { const s = wp(id).shop; return { qty: s.stock[0].qty, price: shopPrice(s, s.stock[0]), n: s.stock[0].n }; }, pid);
  const gpOf = () => p.evaluate(() => { const c = PCS.roster[0].coins; return (+c.gp || 0) + (+c.pp || 0) * 10 + (+c.sp || 0) / 10 + (+c.cp || 0) / 100 + (+c.ep || 0) / 2; });
  const before = await gpOf();
  await p.click('#itShop [data-shopbuy="0"]');
  const after = await gpOf();
  check("Buy pays the shown price, with the markup", Math.abs(after - (before - it0.price)) < 0.02, `${after} vs ${before - it0.price}`);
  check("Buy puts the item in the character's inventory", await p.evaluate(n => (PCS.roster[0].inv || []).some(i => i.n === n), it0.n));
  check("For sale shows the marked-up price", await p.evaluate(id => wp(id).sections[0].x === shopSaleText(wp(id).shop) && wp(id).sections[0].x.includes(fmtGp(shopPrice(wp(id).shop, wp(id).shop.stock[3]))), pid));
  await p.waitForTimeout(700); await p.reload(); await p.waitForFunction(() => typeof shopMake === "function");
  check("what's sold stays sold after a reload", await p.evaluate(([id, q]) => wp(id).shop.stock[0].qty === q - 1, [pid, it0.qty]));
  await p.evaluate(id => { const pl = wp(id); pl.sections[0].x = "mine"; worldSave(); shopOpen(pl); }, pid); await p.waitForTimeout(300);
  await p.click('#itShop [data-shopbuy="1"]'); await p.waitForTimeout(100);
  check("a hand-edited For sale list is left alone", await p.evaluate(id => wp(id).sections[0].x === "mine", pid));
  const keep = await p.evaluate(id => { const s = wp(id).shop; s.stock[0].own = 3; return { seed: s.seed, name: s.name, keeper: s.keeper, moodIx: s.moodIx, id0: s.stock[0].id }; }, pid);
  await p.click("#shopRestock"); await p.click("#modalYes"); await p.waitForTimeout(200);
  const rs = await p.evaluate(([id, k]) => { const s = wp(id).shop, x = s.stock.find(y => y.id === k.id0); return { seed: s.seed !== k.seed, same: s.name === k.name && s.keeper === k.keeper && s.moodIx === k.moodIx && s.markup === 20, own: !x || x.own === 3 }; }, [pid, keep]);
  check("Restock rolls new stock", rs.seed);
  check("Restock keeps the name, shopkeeper, manner and markup", rs.same, JSON.stringify(rs));
  check("Restock keeps your own prices", rs.own);
  await p.evaluate(id => { W.places = W.places.filter(x => x.id !== id); worldSave(); }, pid);
  await p.click('#itShop [data-shopbuy="2"]'); await p.waitForTimeout(100);
  check("no page errors", errs.length === 0, errs.join(" | "));
  await browser.close(); server.close();
  console.log(fails ? `\n${fails} check(s) failed` : "\nAll shop checks passed");
  process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
